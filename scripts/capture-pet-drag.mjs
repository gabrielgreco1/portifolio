import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin=process.env.TEST_ORIGIN||'http://localhost:4323';
const output='/tmp/tamagotchi-drag';await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:2});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto(`${origin}/pt`);await page.waitForTimeout(800);
const pet=page.locator('.crawler-pet'),r=await pet.boundingBox(),x=r.x+r.width/2,y=r.y+r.height/2;
await page.mouse.move(x,y);await page.mouse.down();
await page.mouse.move(x-36,y,{steps:8});await page.screenshot({path:`${output}/01-yield.png`,clip:{x:880,y:580,width:400,height:320}});
await page.mouse.move(x-240,y-5,{steps:20});await page.waitForTimeout(700);
assert.equal(await page.locator('canvas[data-grip]').getAttribute('data-grip'),'1.00');
await page.screenshot({path:`${output}/02-grip.png`,clip:{x:880,y:580,width:400,height:320}});
await page.mouse.move(x-400,y-5,{steps:10});await page.waitForTimeout(100);
await page.screenshot({path:`${output}/03-hold.png`,clip:{x:880,y:580,width:400,height:320}});
await page.mouse.up();await page.waitForTimeout(800);
assert.equal(await page.locator('[data-pet-performance]').count(),0);
assert.equal(await page.getByRole('dialog').count(),0,'Dragging must not open the menu');
await pet.focus();await page.keyboard.down('ArrowLeft');await page.waitForTimeout(80);await page.keyboard.down('ArrowLeft');
assert.equal(await page.locator('[data-pet-performance]').getAttribute('data-pet-performance'),'drag');
await page.keyboard.up('ArrowLeft');await page.waitForTimeout(800);
await pet.press('Enter');await page.getByRole('dialog',{name:'Menu do Tamagotchi'}).waitFor();
await page.keyboard.press('Escape');assert.equal(await pet.getAttribute('aria-expanded'),'false');
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const phone=await mobile.newPage();await phone.goto(`${origin}/pt`);await phone.waitForTimeout(700);
const touch=await mobile.newCDPSession(phone),rect=await phone.locator('.crawler-pet').boundingBox();
const point={x:rect.x+rect.width/2,y:rect.y+rect.height/2};
await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});
await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:point.x-160,y:point.y-20}]});
await phone.waitForTimeout(700);
assert.equal(await phone.locator('[data-pet-performance]').getAttribute('data-pet-performance'),'drag');
await phone.screenshot({path:`${output}/04-touch.png`});
await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await phone.waitForTimeout(800);
assert.equal(await phone.locator('[data-pet-performance]').count(),0);
assert.equal(await phone.getByRole('dialog').count(),0);
assert.deepEqual(errors,[]);await browser.close();console.log(`Drag, grip, click suppression, keyboard and touch passed; frames: ${output}`);
